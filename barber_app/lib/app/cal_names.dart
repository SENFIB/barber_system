/// ارقام بر اساس زبان
String localDigits(Object v, String lang) {
  final s = '$v';
  if (lang == 'en') return s;
  final base = lang == 'ar' ? 0x0660 : 0x06F0;
  final sb = StringBuffer();
  for (final r in s.runes) {
    if (r >= 0x30 && r <= 0x39) {
      sb.writeCharCode(base + r - 0x30);
    } else {
      sb.writeCharCode(r);
    }
  }
  return sb.toString();
}

