  final String lang;

  String t(String key, [Map<String, Object?>? args]) {
    var r = _m[lang]?[key] ?? _m['en']![key] ?? key;
    if (args != null) {
      args.forEach((k, v) => r = r.replaceAll('{$k}', '$v'));
    }
    return r;
  }

  bool has(String key) =>
      (_m[lang]?.containsKey(key) ?? false) || _m['en']!.containsKey(key);

  String error(Object e) {
    if (e is ApiException) {
      final k = 'err_${e.code}';
      if (has(k)) return t(k);
      return e.message.isNotEmpty ? e.message : t('err_generic');
    }
    return t('err_generic');
  }
